"""Narration from per-scene clips, so nobody has to tap cues by hand.

  python scripts/narration.py export
      writes docs/narration-script.{fr,en}.md: the 58 scene scripts, numbered, to read or paste into a
      text-to-speech tool one scene at a time.

  python scripts/narration.py assemble <lang> <folder>
      reads <folder>/scene-01.mp3 ... scene-58.mp3 (any format ffmpeg reads; missing scenes are skipped), joins
      them with a short pause, and writes public/audio/narration.<lang>.mp3 (mono, 96 kbps) and
      content/narration/cues.<lang>.json (each scene starts where its clip starts).

Needs ffmpeg, numpy and PyYAML.
"""

import json
import subprocess
import sys
from pathlib import Path

import numpy as np
import yaml

ROOT = Path(__file__).resolve().parent.parent
SR = 44100
LEAD, GAP = 0.6, 1.2  # seconds of silence before the first scene and between scenes


def scenes() -> list[dict]:
    return yaml.safe_load((ROOT / "content" / "scenes.yaml").read_text())


def export() -> None:
    for lang, heading in (("fr", "Script de narration"), ("en", "Narration script")):
        lines = [f"# {heading} ({lang})", "", "Generated by `python scripts/narration.py export` from content/scenes.yaml.", ""]
        for scene in scenes():
            lines += [f"## scene-{scene['n']:02d} · {scene['title'][lang]}", "", scene["script"][lang].strip(), ""]
        (ROOT / "docs" / f"narration-script.{lang}.md").write_text("\n".join(lines))
    print("written docs/narration-script.{fr,en}.md")


def decode(path: Path) -> np.ndarray:
    raw = subprocess.run(
        ["ffmpeg", "-v", "error", "-i", str(path), "-ac", "1", "-ar", str(SR), "-f", "f32le", "pipe:1"],
        capture_output=True, check=True,
    ).stdout
    return np.frombuffer(raw, dtype=np.float32)


def trim(x: np.ndarray, threshold: float = 0.01) -> np.ndarray:
    """Drops the silence a TTS tool leaves at both ends, keeping 50 ms."""
    loud = np.flatnonzero(np.abs(x) > threshold)
    if len(loud) == 0:
        return x
    pad = int(SR * 0.05)
    return x[max(0, loud[0] - pad) : loud[-1] + pad]


def assemble(lang: str, folder: Path) -> None:
    parts, cues, t = [np.zeros(int(SR * LEAD), np.float32)], [], LEAD
    for scene in scenes():
        clip = next(iter(sorted(folder.glob(f"scene-{scene['n']:02d}.*"))), None)
        if clip is None:
            print(f"scene {scene['n']}: no clip, skipped")
            continue
        x = trim(decode(clip))
        cues.append({"t": round(t, 2), "scene": scene["n"]})
        parts += [x, np.zeros(int(SR * GAP), np.float32)]
        t += len(x) / SR + GAP
    audio = np.concatenate(parts)
    audio *= 10 ** (-1 / 20) / (np.abs(audio).max() or 1)
    out = ROOT / "public" / "audio" / f"narration.{lang}.mp3"
    out.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(
        ["ffmpeg", "-v", "error", "-y", "-f", "f32le", "-ar", str(SR), "-ac", "1", "-i", "pipe:0",
         "-codec:a", "libmp3lame", "-b:a", "96k", "-map_metadata", "-1", str(out)],
        input=audio.astype(np.float32).tobytes(), check=True,
    )
    (ROOT / "content" / "narration" / f"cues.{lang}.json").write_text(json.dumps(cues, indent=1) + "\n")
    print(f"{lang}: {len(cues)} scenes, {t / 60:.1f} min -> {out.relative_to(ROOT)}")


if __name__ == "__main__":
    if sys.argv[1:2] == ["export"]:
        export()
    elif sys.argv[1:2] == ["assemble"] and len(sys.argv) == 4:
        assemble(sys.argv[2], Path(sys.argv[3]))
    else:
        sys.exit(__doc__)

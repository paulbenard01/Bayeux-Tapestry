// Builds docs/review.md: what still needs Paul's review, every "check" note, and sources to verify.
// Shared by `npm run review` (writes the file) and tests/content.test.ts (checks it is current).
import { readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";
import yaml from "js-yaml";

export function loadContent(root) {
  const read = (p) => yaml.load(readFileSync(join(root, p), "utf8"));
  return {
    scenes: read("content/scenes.yaml"),
    stories: read("content/stories.yaml"),
    hotspots: read("content/hotspots.yaml"),
    sources: read("content/sources.yaml"),
    layers: readdirSync(join(root, "layers"))
      .filter((f) => f.endsWith(".yaml"))
      .sort()
      .map((f) => read(`layers/${f}`)),
  };
}

function tally(items) {
  const reviewed = items.filter((x) => x.review_status === "reviewed").length;
  const lang = items.filter((x) => x.lang_review === "reviewed").length;
  return `${reviewed}/${items.length} reviewed, ${lang}/${items.length} language-reviewed`;
}

export function reviewReport({ scenes, stories, hotspots, sources, layers }) {
  const lines = [
    "# Review checklist",
    "",
    "Generated by `npm run review`; a test fails if it is out of date. Set `review_status: reviewed` and",
    "`lang_review: reviewed` in the content files once a text is checked, and `status: checked` on a source",
    "once its reference is confirmed.",
    "",
    "## Progress",
    "",
    `- Scenes: ${tally(scenes)}`,
    `- Stories: ${tally(stories)}`,
    `- Hotspots: ${tally(hotspots)}`,
    `- Sources: ${Object.values(sources).filter((s) => s.status === "checked").length}/${Object.keys(sources).length} checked`,
    ...layers.map(
      (layer) =>
        `- Image layer \`${layer.id}\`: ${layer.available ? "tiles available" : "tiles not generated yet"}, ${
          layer.calibrated ? "scenes calibrated" : "scene positions not checked on this image"
        }`,
    ),
    "",
    "## Facts to check",
    "",
  ];
  const checks = [
    ...scenes.filter((s) => s.check).map((s) => `- Scene ${s.n}: ${s.check}`),
    ...stories.filter((s) => s.check).map((s) => `- Story \`${s.id}\` (scene ${s.scene}): ${s.check}`),
    ...hotspots.filter((h) => h.check).map((h) => `- Hotspot \`${h.id}\` (scene ${h.scene}): ${h.check}`),
  ];
  lines.push(...(checks.length ? checks : ["None."]), "", "## Sources to confirm", "");
  const toCheck = Object.entries(sources).filter(([, s]) => s.status !== "checked");
  lines.push(...(toCheck.length ? toCheck.map(([k, s]) => `- \`${k}\`: ${s.citation}`) : ["None."]), "");
  return lines.join("\n");
}
